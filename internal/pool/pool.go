// Пакет pool даёт типобезопасный пул переиспользуемых объектов поверх sync.Pool.
//
// Стандартный sync.Pool хранит значения типа any: на каждом получении объекта
// приходится приводить тип, а положить в пул можно что угодно. Обобщённая
// обёртка снимает обе проблемы — Get возвращает готовый указатель нужного типа,
// а Put принимает только его.
//
// Объект обязан уметь сбрасывать своё состояние: возвращать в пул грязный
// объект опасно, следующий владелец получил бы чужие данные. Метод Reset
// пишется руками или генерируется командой cmd/reset по маркеру
// // generate:reset.
package pool

import "sync"

// Resettable описывает указатель на T, умеющий сбрасывать своё состояние.
// Ограничение записано через *T, поэтому пул сам создаёт объекты и не требует
// фабрики, а тип указателя выводится компилятором из T.
type Resettable[T any] interface {
	*T
	Reset()
}

// Pool хранит объекты одного типа для повторного использования.
// Нулевое значение непригодно к работе, пул создаётся функцией New.
type Pool[T any, P Resettable[T]] struct {
	objects sync.Pool
}

// New создаёт пул объектов типа T:
//
//	p := pool.New[models.UserURLItem]()
//	item := p.Get()
//	defer p.Put(item)
func New[T any, P Resettable[T]]() *Pool[T, P] {
	return &Pool[T, P]{
		objects: sync.Pool{
			New: func() any { return P(new(T)) },
		},
	}
}

// Get возвращает объект из пула. Если пул пуст, создаётся новый объект в
// начальном состоянии: функция New поля objects задана в конструкторе, поэтому
// пустого результата не бывает.
func (p *Pool[T, P]) Get() P {
	return p.objects.Get().(P)
}

// Put сбрасывает состояние объекта и возвращает его в пул. Пустой указатель
// игнорируется: класть nil в пул бессмысленно, а Get вернул бы его как готовый
// объект и вызвал бы панику у владельца.
func (p *Pool[T, P]) Put(obj P) {
	if obj == nil {
		return
	}
	obj.Reset()
	p.objects.Put(obj)
}
