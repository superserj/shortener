// Команда reset генерирует методы Reset для структур, помеченных
// комментарием // generate:reset.
//
// Утилита сканирует пакеты проекта, начиная с корневой директории и ниже, и для
// каждого пакета с помеченными структурами создаёт файл reset.gen.go с методами
// сброса. Метод возвращает объект к начальному состоянию, сохраняя выделенную
// память: слайсы обрезаются по длине, мапы очищаются встроенным clear.
//
// Запуск из корня проекта:
//
//	go run ./cmd/reset
//
// Директорию можно задать явно:
//
//	go run ./cmd/reset -dir ./internal
package main

import (
	"flag"
	"log"
)

func main() {
	dir := flag.String("dir", ".", "корневая директория, с которой начинается сканирование пакетов")
	flag.Parse()

	generated, err := generate(*dir)
	if err != nil {
		log.Fatalf("генерация методов Reset: %v", err)
	}
	for _, file := range generated {
		log.Printf("сгенерирован %s", file)
	}
}
